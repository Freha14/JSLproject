CREATE TABLE DELIVERY_REQUEST (
    REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MEMBER_ID VARCHAR2(100) NOT NULL,
    CENTER_CODE VARCHAR2(30) NOT NULL,
    ORDER_NUMBER VARCHAR2(100),
    RECIPIENT_NAME VARCHAR2(100) NOT NULL,
    RECIPIENT_PHONE VARCHAR2(30) NOT NULL,
    RECIPIENT_POSTCODE VARCHAR2(20),
    RECIPIENT_ADDRESS VARCHAR2(500) NOT NULL,
    REQUEST_MEMO VARCHAR2(1000),
    REQUEST_STATUS VARCHAR2(20) DEFAULT 'REQUESTED' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_DELIVERY_STATUS CHECK
      (REQUEST_STATUS IN ('REQUESTED','ARRIVED','PREPARING','SHIPPED','DELIVERED','CANCELLED'))
);

CREATE TABLE DELIVERY_PRODUCT (
    PRODUCT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REQUEST_ID NUMBER NOT NULL,
    PRODUCT_NAME VARCHAR2(200) NOT NULL,
    PRODUCT_URL VARCHAR2(1000),
    QUANTITY NUMBER(8) NOT NULL,
    UNIT_PRICE NUMBER(12,2) NOT NULL,
    PRODUCT_CATEGORY VARCHAR2(100),
    CONSTRAINT FK_DELIVERY_PRODUCT_REQUEST FOREIGN KEY (REQUEST_ID)
      REFERENCES DELIVERY_REQUEST(REQUEST_ID) ON DELETE CASCADE,
    CONSTRAINT CK_DELIVERY_PRODUCT_QTY CHECK (QUANTITY > 0),
    CONSTRAINT CK_DELIVERY_PRODUCT_PRICE CHECK (UNIT_PRICE >= 0)
);

CREATE INDEX IDX_DELIVERY_REQUEST_MEMBER ON DELIVERY_REQUEST(MEMBER_ID, CREATED_AT);
CREATE INDEX IDX_DELIVERY_PRODUCT_REQUEST ON DELIVERY_PRODUCT(REQUEST_ID);
